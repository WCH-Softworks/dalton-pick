#!/usr/bin/env node
// Turns docs/store/privacy-policy.{en,es,pt-BR}.md into the DaltonPick privacy pages on willcaphir.com.
//
//   node scripts/export-privacy.mjs [path to the willcaphir.com repo]   (default: ../willcaphir)
//
// Run it from this repo's root after any change to a policy file, then review, commit and push the
// willcaphir.com repo. It writes public/daltonpick/{,es/,pt-BR/}privacy/index.html there.
// No dependencies: the converter handles only the Markdown the policies use (# and ## headings,
// "- " lists, paragraphs, **bold**, *italic*, [text](url) and <autolinks>). It stops with an error on
// anything else, so a new construct in a policy can't silently render wrong.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";

const site = resolve(process.argv[2] ?? "../willcaphir");
const ORIGIN = "https://willcaphir.com";
const BASE = "/daltonpick/";

const LANGS = {
  en: { root: BASE, name: "English", title: "Privacy policy", skip: "Skip to content", languages: "Language",
    source: "Source code", report: "Report a bug", kofi: "Support on Ko-fi",
    madeBy: 'Made by <a href="/">WCH Softworks</a>. Free, no ads, no tracking, no internet.' },
  es: { root: `${BASE}es/`, name: "Español", title: "Política de privacidad", skip: "Saltar al contenido", languages: "Idioma",
    source: "Código fuente", report: "Reportar un error", kofi: "Apoyar en Ko-fi",
    madeBy: 'Hecho por <a href="/">WCH Softworks</a>. Gratis, sin anuncios, sin rastreo, sin Internet.' },
  "pt-BR": { root: `${BASE}pt-BR/`, name: "Português (Brasil)", title: "Política de privacidade", skip: "Pular para o conteúdo", languages: "Idioma",
    source: "Código-fonte", report: "Relatar um erro", kofi: "Apoiar no Ko-fi",
    madeBy: 'Feito por <a href="/">WCH Softworks</a>. Grátis, sem anúncios, sem rastreamento, sem internet.' },
};
const GITHUB = "https://github.com/WCH-Softworks/dalton-pick";
const ISSUES = "https://github.com/WCH-Softworks/dalton-pick/issues/new/choose";
const KOFI = "https://ko-fi.com/willcaphir";

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function inline(text, where) {
  const saved = [];
  const keep = (html) => `\u0000${saved.push(html) - 1}\u0000`;
  let s = text
    .replace(/<(https?:\/\/[^>\s]+)>/g, (_, u) => keep(`<a href="${esc(u)}">${esc(u)}</a>`))
    .replace(/<([^>\s@]+@[^>\s]+)>/g, (_, m) => keep(`<a href="mailto:${esc(m)}">${esc(m)}</a>`))
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, u) => keep(`<a href="${esc(u)}">${emphasis(esc(t))}</a>`));
  if (/[<>`]|\[|\]\(/.test(s)) throw new Error(`${where}: unsupported Markdown: ${text}`);
  s = emphasis(esc(s));
  if (/\*/.test(s)) throw new Error(`${where}: unmatched * in: ${text}`);
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => saved[i]);
}
const emphasis = (s) => s.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>").replace(/\*(.+?)\*/g, "<em>$1</em>");

const slug = (s) => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "")
  .replace(/[^a-z0-9\s-]/g, "").trim().replace(/\s+/g, "-");

function convert(md, where) {
  const out = [];
  let para = [], list = null;
  const flush = () => {
    if (para.length) out.push(`<p>${inline(para.join(" "), where)}</p>`);
    if (list) out.push(`<ul>\n${list.map((li) => `  <li>${inline(li, where)}</li>`).join("\n")}\n</ul>`);
    para = []; list = null;
  };
  md.split(/\r?\n/).forEach((line, n) => {
    const at = `${where}:${n + 1}`;
    let m;
    if (!line.trim()) flush();
    else if ((m = /^(#{1,2}) (.+)$/.exec(line))) {
      flush();
      const h = m[1].length;
      out.push(h === 1 ? `<h1>${inline(m[2], at)}</h1>` : `<h2 id="${slug(m[2])}">${inline(m[2], at)}</h2>`);
    } else if ((m = /^- (.+)$/.exec(line))) {
      if (para.length) flush();
      (list ??= []).push(m[1]);
    } else if (/^(#|>|\d+\.|\s|\||```)/.test(line)) throw new Error(`${at}: unsupported Markdown: ${line}`);
    else {
      if (list) flush();
      para.push(line.trim());
    }
  });
  flush();
  return out.join("\n");
}

function page(lang, body) {
  const t = LANGS[lang];
  const alternates = Object.entries(LANGS)
    .map(([l, o]) => `  <link rel="alternate" hreflang="${l}" href="${ORIGIN}${o.root}privacy/">`).join("\n");
  const switcher = Object.entries(LANGS)
    .map(([l, o]) => `        <li><a href="${o.root}privacy/" hreflang="${l}" lang="${l}"${l === lang ? ' aria-current="page"' : ""}>${o.name}</a></li>`)
    .join("\n");
  return `<!doctype html>
<!-- Generated by scripts/export-privacy.mjs in the DaltonPick repo from docs/store/privacy-policy.${lang}.md. Don't edit by hand. -->
<html lang="${lang}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${t.title} · DaltonPick</title>
  <link rel="canonical" href="${ORIGIN}${t.root}privacy/">
  <link rel="icon" href="${BASE}assets/icon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="${BASE}assets/style.css">
${alternates}
  <link rel="alternate" hreflang="x-default" href="${ORIGIN}${BASE}privacy/">
</head>
<body>
  <a class="skip" href="#main">${t.skip}</a>
  <header class="top">
    <a class="brand" href="${t.root}">
      <span class="logo" aria-hidden="true"><img src="${BASE}assets/icon.svg" alt="" width="40" height="40"></span>
      <span>DaltonPick</span>
    </a>
    <nav aria-label="${t.languages}" class="langs">
      <ul>
${switcher}
      </ul>
    </nav>
  </header>
  <main id="main" class="privacy">
${body}
  </main>
  <footer class="bottom">
    <ul>
      <li><a href="${t.root}privacy/" aria-current="page">${t.title}</a></li>
      <li><a href="${GITHUB}">${t.source}</a></li>
      <li><a href="${ISSUES}">${t.report}</a></li>
      <li><a href="${KOFI}">${t.kofi}</a></li>
    </ul>
    <p>${t.madeBy}</p>
  </footer>
</body>
</html>
`;
}

for (const lang of Object.keys(LANGS)) {
  const src = `docs/store/privacy-policy.${lang}.md`;
  const html = page(lang, convert(readFileSync(src, "utf8"), src));
  const dir = join(site, "public", ...LANGS[lang].root.split("/").filter(Boolean), "privacy");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "index.html"), html);
  console.log(`${src} -> ${join(dir, "index.html")}`);
}
